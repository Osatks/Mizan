#!/usr/bin/env python3
"""Generates i18n/pack/PackStrings.kt from the Strings interface.

PackStrings implements every member of Strings by reading a language pack (JSON), falling back to
English for anything the pack lacks. Run it after adding keys to Strings.kt:

    python3 tools/gen_pack_strings.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shared/src/commonMain/kotlin/com/osatks/mizan/i18n/Strings.kt"
OUT = ROOT / "shared/src/commonMain/kotlin/com/osatks/mizan/i18n/pack/PackStrings.kt"

# Written by hand below: they need data beyond their arguments (month names, enum keys)
SPECIAL = {"hijriDate", "gregDate", "hijriMonthTitle", "monthTableTitle", "shareType", "inhNote", "livestockKind", "nameOf"}

member = re.compile(r"^\s*(val|fun) (\w+)(\(([^)]*)\))?: ([A-Za-z<>, ]+?)\s*(//.*)?$")

lines = []
for line in SRC.read_text().splitlines():
    m = member.match(line)
    if not m:
        continue
    kind, name, _, params, typ = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5).strip()
    if name in SPECIAL:
        continue
    if kind == "val":
        helper = {
            "String": None,
            "List<String>": "list",
            "Map<String, String>": "map",
            "Map<String, Named>": "named",
            "List<Pair<String, String>>": "pairs",
        }[typ]
        if helper is None:
            lines.append(f'    override val {name}: String by lazy {{ s("{name}") ?: En.{name} }}')
        else:
            lines.append(f'    override val {name}: {typ} by lazy {{ {helper}("{name}", En.{name}) }}')
    else:
        ps = [p.strip() for p in params.split(",") if p.strip()]
        names = [p.split(":")[0].strip() for p in ps]
        vars_ = "".join(f', "{n}" to {n}' for n in names)
        lines.append(f'    override fun {name}({", ".join(ps)}): String = f("{name}"{vars_}) ?: En.{name}({", ".join(names)})')

OUT.write_text(f'''package com.osatks.mizan.i18n.pack

import com.osatks.mizan.core.InhNote
import com.osatks.mizan.core.ShareType
import com.osatks.mizan.i18n.En
import com.osatks.mizan.i18n.Named
import com.osatks.mizan.i18n.Strings

// Generated by tools/gen_pack_strings.py from Strings.kt — do not edit by hand.

/**
 * نصوص لغة من حزمة JSON. كل نص ناقص في الحزمة يُعرض بالإنجليزية، فتعمل الحزم القديمة مع إصدارات أحدث.
 * Every member reads the pack; anything missing falls back to English.
 */
class PackStrings(private val pack: LangPack) : Strings {{
    private val m = pack.strings

    private fun s(k: String): String? = (m[k] as? String)?.takeIf {{ it.isNotBlank() }}

    private fun f(k: String, vararg vars: Pair<String, Any>): String? = s(k)?.let {{ Template.format(it, mapOf(*vars), pack.code) }}

    /** قائمة بطول القائمة الإنجليزية نفسه؛ كل عنصر ناقص يؤخذ منها */
    private fun list(k: String, en: List<String>): List<String> {{
        val l = m[k] as? List<*> ?: return en
        if (l.size != en.size) return en
        return en.indices.map {{ (l[it] as? String)?.takeIf {{ s -> s.isNotBlank() }} ?: en[it] }}
    }}

    private fun map(k: String, en: Map<String, String>): Map<String, String> {{
        val p = m[k] as? Map<*, *> ?: return en
        return en.mapValues {{ (key, v) -> (p[key] as? String)?.takeIf {{ it.isNotBlank() }} ?: v }}
    }}

    private fun named(k: String, en: Map<String, Named>): Map<String, Named> {{
        val p = m[k] as? Map<*, *> ?: return en
        return en.mapValues {{ (key, v) ->
            val o = p[key] as? Map<*, *>
            Named((o?.get("name") as? String)?.takeIf {{ it.isNotBlank() }} ?: v.name, (o?.get("desc") as? String)?.takeIf {{ it.isNotBlank() }} ?: v.desc)
        }}
    }}

    private fun pairs(k: String, en: List<Pair<String, String>>): List<Pair<String, String>> {{
        val l = m[k] as? List<*> ?: return en
        if (l.size != en.size) return en
        return en.indices.map {{ i ->
            val p = l[i] as? List<*>
            ((p?.getOrNull(0) as? String) ?: en[i].first) to ((p?.getOrNull(1) as? String) ?: en[i].second)
        }}
    }}

    /** مفتاح داخل خريطة نصية في الحزمة (shareType، inhNote، livestockKind) */
    private fun sub(k: String, key: String): String? = ((m[k] as? Map<*, *>)?.get(key) as? String)?.takeIf {{ it.isNotBlank() }}

    // ---------- Hand-written: values that need more than the arguments ----------

    override fun hijriDate(d: Int, m: Int, y: Int): String =
        f("hijriDate", "d" to d, "m" to m, "y" to y, "month" to hijriMonths[m - 1]) ?: En.hijriDate(d, m, y)
    override fun gregDate(d: Int, m: Int, y: Int): String =
        f("gregDate", "d" to d, "m" to m, "y" to y, "month" to gregMonths[m - 1]) ?: En.gregDate(d, m, y)
    override fun hijriMonthTitle(m: Int, y: Int): String =
        f("hijriMonthTitle", "m" to m, "y" to y, "month" to hijriMonths[m - 1]) ?: En.hijriMonthTitle(m, y)
    override fun monthTableTitle(m: Int, y: Int): String =
        f("monthTableTitle", "m" to m, "y" to y, "month" to gregMonths[m - 1]) ?: En.monthTableTitle(m, y)

    /** "shareType": {{"FARD": "…", …, "radd": "{{type}} + radd"}} */
    override fun shareType(t: ShareType, radd: Boolean): String {{
        val base = sub("shareType", t.name) ?: return En.shareType(t, radd)
        if (!radd) return base
        return sub("shareType", "radd")?.let {{ Template.format(it, mapOf("type" to base), pack.code) }} ?: En.shareType(t, true)
    }}

    /** "inhNote": مفتاح لكل ملاحظة؛ JaddRule و JaddRuleOtherFard، و{{winner}} و{{asl}} و{{awl}} */
    override fun inhNote(n: InhNote): String {{
        val key = when (n) {{
            is InhNote.JaddRule -> if (n.otherFard) "JaddRuleOtherFard" else "JaddRule"
            else -> n::class.simpleName ?: ""
        }}
        val t = sub("inhNote", key) ?: return En.inhNote(n)
        val vars = when (n) {{
            is InhNote.NothingLeft -> mapOf("winner" to nameOf(n.winner))
            is InhNote.Awl -> mapOf("asl" to n.asl, "awl" to n.awl)
            else -> emptyMap()
        }}
        return Template.format(t, vars, pack.code)
    }}

    override fun livestockKind(kind: String): String = sub("livestockKind", kind) ?: En.livestockKind(kind)

    // ---------- Generated ----------

{chr(10).join(lines)}
}}
''')
print(f"{len(lines)} members -> {OUT.relative_to(ROOT)}")
