    fun index(surah: Int, ayah: Int): Int = STARTS[surah - 1] + ayah - 1

    /** (السورة، الآية) من الفهرس العام */
    fun locate(index: Int): Pair<Int, Int> {
        var lo = 0; var hi = SURAHS - 1
        while (lo < hi) {
            val mid = (lo + hi + 1) / 2
            if (STARTS[mid] <= index) lo = mid else hi = mid - 1
        }
        return (lo + 1) to (index - STARTS[lo] + 1)
    }

